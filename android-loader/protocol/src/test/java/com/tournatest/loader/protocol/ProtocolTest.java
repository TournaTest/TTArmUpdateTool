package com.tournatest.loader.protocol;

import org.junit.Test;

import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.nio.ByteBuffer;
import java.nio.ByteOrder;
import java.nio.charset.StandardCharsets;
import java.util.ArrayDeque;
import java.util.Arrays;

import static org.junit.Assert.*;

public class ProtocolTest {
    @Test public void crcMatchesStandardCheckVector() {
        assertEquals(0x29b1, Crc16.calculate("123456789".getBytes(StandardCharsets.US_ASCII)));
    }

    @Test public void framesMatchUnmodifiedAdafruitNrfutilGoldenVectors() {
        // Generated by executing upstream HciPacket, util.py, and crc16.py, not this implementation.
        golden(1, "03000000040000000000000000000000a44e0200",
                "c0d14e01e003000000040000000000000000000000a44e020022efc0");
        golden(2, "010000005200ffffffffffff0100b70074160000",
                "c0da4e01d7010000005200ffffffffffff0100b700741600008d11c0");
        golden(3, "0400000000c0dbff10203040",
                "c0e3ce004f0400000000dbdcdbddff10203040f5c2c0");
        golden(0, "05000000", "c0c84e00ea05000000360ac0");
    }

    @Test public void decoderPreservesFragmentedEscapesAndCoalescedFrames() throws Exception {
        HciCodec.Decoder decoder = new HciCodec.Decoder();
        byte[] wire = HciCodec.slip(hex("c0db01"));
        byte[] ack = HciCodec.slip(hex("100000f0"));
        ByteArrayOutputStream input = new ByteArrayOutputStream();
        input.write(1); input.write(2); // Noise before the first delimiter.
        input.write(wire, 0, wire.length);
        input.write(ack, 0, ack.length);
        for (byte b : input.toByteArray()) decoder.accept(new byte[]{b}, 1);
        assertArrayEquals(hex("c0db01"), decoder.poll());
        assertEquals(2, HciCodec.acknowledgement(decoder.poll()));
        assertNull(decoder.poll());
    }

    @Test public void decoderResynchronizesAfterBrokenAndOversizeFrames() throws Exception {
        HciCodec.Decoder decoder = new HciCodec.Decoder();
        byte[] invalid = hex("c001db00c0");
        decoder.accept(invalid, invalid.length);
        byte[] large = new byte[5000];
        decoder.accept(large, large.length);
        byte[] valid = HciCodec.slip(hex("080000f8"));
        decoder.accept(valid, valid.length);
        assertEquals(1, HciCodec.acknowledgement(decoder.poll()));
        assertNull(decoder.poll());
    }

    @Test public void ackRejectsBadChecksumLengthAndPacketType() throws Exception {
        for (String invalid : new String[]{"10", "100000f1", "100100ef", "101000e0", "90000070", "100000f000"}) {
            assertThrows(IOException.class, () -> HciCodec.acknowledgement(hex(invalid)));
        }
        assertEquals(0, HciCodec.acknowledgement(hex("00000000")));
        assertEquals(7, HciCodec.acknowledgement(hex("380000c8")));
    }

    @Test public void detectorMatchesSignatureAcrossReadsAfterDtrReset() throws Exception {
        FakeTime clock = new FakeTime();
        FakePort port = new FakePort(clock);
        port.text = "noise\r\nInitializing channels\r\n".getBytes(StandardCharsets.US_ASCII);
        port.chunk = 3;
        TournaTestDetector.identify(port, clock);
        assertEquals("010", port.dtr.toString());
        assertTrue(port.writes.isEmpty());
    }

    @Test public void detectorTimesOutWithoutWritingToUnknownDevice() {
        FakeTime clock = new FakeTime();
        FakePort port = new FakePort(clock);
        port.text = "another device".getBytes(StandardCharsets.US_ASCII);
        assertThrows(IOException.class, () -> TournaTestDetector.identify(port, clock));
        assertTrue(clock.now >= 15_100);
        assertTrue(port.writes.isEmpty());
    }

    @Test public void transferMatchesFirmwareAndSequenceWrapWithFragmentedAcks() throws Exception {
        FakeTime clock = new FakeTime();
        FakePort port = new FakePort(clock);
        port.chunk = 1;
        FirmwarePackage firmware = FirmwarePackageTest.realFirmware();
        int[] progress = {0};
        new LegacyDfu(port, clock, (message, percent) -> {
            assertTrue(percent >= progress[0]);
            progress[0] = percent;
        }).transfer(firmware);
        assertArrayEquals(firmware.application(), port.received.toByteArray());
        assertArrayEquals(firmware.initPacket(), port.receivedInit);
        assertEquals(firmware.size(), port.declaredSize);
        assertEquals(1, port.stops);
        assertEquals(99, progress[0]);
        assertEquals("01", port.dtr.toString());
        assertTrue("Retain erase, flash pacing and activation delays", clock.slept >= 14_000);
    }

    @Test public void lostAckRetriesIdenticalPacketWithoutDuplicatingFirmware() throws Exception {
        FakeTime clock = new FakeTime();
        FakePort port = new FakePort(clock);
        port.dropAckAt = 4;
        FirmwarePackage firmware = FirmwarePackageTest.realFirmware();
        new LegacyDfu(port, clock, (message, percent) -> {}).transfer(firmware);
        assertArrayEquals(firmware.application(), port.received.toByteArray());
        assertArrayEquals(port.writes.toArray(new byte[0][])[3], port.writes.toArray(new byte[0][])[4]);
        assertEquals(1, port.duplicates);
    }

    @Test public void corruptAndStaleAcksCannotAdvanceTransfer() throws Exception {
        FakeTime clock = new FakeTime();
        FakePort port = new FakePort(clock);
        port.prependStaleAndCorruptAck = true;
        FirmwarePackage firmware = FirmwarePackageTest.realFirmware();
        new LegacyDfu(port, clock, (message, percent) -> {}).transfer(firmware);
        assertArrayEquals(firmware.application(), port.received.toByteArray());
        assertEquals(0, port.duplicates);
    }

    @Test public void missingAckFailsAfterThreeAttemptsWithoutSendingInitOrFirmware() throws Exception {
        FakeTime clock = new FakeTime();
        FakePort port = new FakePort(clock);
        port.suppressAllAcks = true;
        assertThrows(IOException.class, () -> new LegacyDfu(port, clock, (message, percent) -> {})
                .transfer(FirmwarePackageTest.realFirmware()));
        assertEquals(3, port.writes.size());
        assertEquals(0, port.received.size());
        assertNull(port.receivedInit);
    }

    @Test public void failedUsbWriteIsNotRetriedAsAWholeFrame() throws Exception {
        FakeTime clock = new FakeTime();
        FakePort port = new FakePort(clock);
        port.failWrite = true;
        assertThrows(IOException.class, () -> new LegacyDfu(port, clock, (message, percent) -> {})
                .transfer(FirmwarePackageTest.realFirmware()));
        assertEquals(1, port.writes.size());
    }

    static byte[] hex(String value) {
        byte[] result = new byte[value.length() / 2];
        for (int i = 0; i < result.length; i++) result[i] = (byte) Integer.parseInt(value.substring(i * 2, i * 2 + 2), 16);
        return result;
    }
    private void golden(int seq, String payload, String expected) {
        assertArrayEquals(hex(expected), HciCodec.packet(seq, hex(payload)));
    }

    static final class FakeTime implements Timing {
        long now;
        long slept;
        @Override public long nowMs() { return now; }
        @Override public void sleep(long ms) { now += ms; slept += ms; }
    }

    /** Models Nordic's sequence validation and duplicate suppression independently of host framing. */
    static final class FakePort implements SerialTransport {
        final FakeTime clock;
        final ArrayDeque<Byte> input = new ArrayDeque<>();
        final ArrayDeque<byte[]> writes = new ArrayDeque<>();
        final ByteArrayOutputStream received = new ByteArrayOutputStream();
        final StringBuilder dtr = new StringBuilder();
        int expected = 1;
        int chunk = 256;
        int dropAckAt = -1;
        int duplicates;
        int declaredSize;
        int stops;
        boolean suppressAllAcks;
        boolean prependStaleAndCorruptAck;
        boolean failWrite;
        byte[] text;
        byte[] receivedInit;
        FakePort(FakeTime clock) { this.clock = clock; }
        @Override public void setDtr(boolean value) {
            dtr.append(value ? '1' : '0');
            if (!value && text != null) { enqueue(text); text = null; }
        }
        @Override public void discardInput() { input.clear(); }
        @Override public void close() {}
        @Override public int read(byte[] data, int timeoutMs) {
            int n = 0;
            while (!input.isEmpty() && n < Math.min(data.length, chunk)) data[n++] = input.remove();
            if (n == 0) clock.now += timeoutMs;
            return n;
        }
        @Override public void write(byte[] data, int timeoutMs) throws IOException {
            writes.add(data.clone());
            if (failWrite) throw new IOException("USB partial-write timeout");
            HciCodec.Decoder decode = new HciCodec.Decoder();
            decode.accept(data, data.length);
            byte[] raw = decode.poll();
            assertNotNull(raw);
            assertEquals(0, ((raw[0] & 255) + (raw[1] & 255) + (raw[2] & 255) + (raw[3] & 255)) & 255);
            int payloadSize = ((raw[1] & 255) >>> 4) | ((raw[2] & 255) << 4);
            assertEquals(payloadSize + 6, raw.length);
            assertEquals(Crc16.calculate(raw, 0, raw.length - 2),
                    (raw[raw.length - 2] & 255) | ((raw[raw.length - 1] & 255) << 8));
            int seq = raw[0] & 7;
            if (seq == expected) {
                expected = (expected + 1) & 7;
                ByteBuffer payload = ByteBuffer.wrap(raw, 4, payloadSize).order(ByteOrder.LITTLE_ENDIAN);
                switch (payload.getInt()) {
                    case 3:
                        assertEquals(4, payload.getInt());
                        assertEquals(0, payload.getInt());
                        assertEquals(0, payload.getInt());
                        declaredSize = payload.getInt();
                        break;
                    case 1:
                        receivedInit = new byte[payload.remaining() - 2];
                        payload.get(receivedInit);
                        assertEquals(0, payload.getShort());
                        break;
                    case 4:
                        received.write(raw, 8, payloadSize - 4);
                        break;
                    case 5:
                        stops++;
                        assertEquals(declaredSize, received.size());
                        break;
                    default: fail("Unknown DFU opcode");
                }
            } else {
                duplicates++;
                assertEquals((expected + 7) & 7, seq);
            }
            if (suppressAllAcks || writes.size() == dropAckAt) return;
            if (prependStaleAndCorruptAck) {
                enqueue(HciCodec.slip(new byte[]{(byte) (seq << 3), 0, 0, (byte) -(seq << 3)}));
                enqueue(HciCodec.slip(new byte[]{0, 0, 0, 1}));
            }
            enqueue(HciCodec.slip(new byte[]{(byte) (expected << 3), 0, 0, (byte) -(expected << 3)}));
        }
        private void enqueue(byte[] data) { for (byte value : data) input.add(value); }
    }
}
